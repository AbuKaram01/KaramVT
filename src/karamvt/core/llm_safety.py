"""Shared defenses against prompt injection via translated text.

Both TranslationEngine (subtitles) and TextTranslationEngine (free text) feed untrusted, potentially
attacker-crafted text into a local LLM. This module is the single implementation of the defense: a random per-job
delimiter, which the model is told to treat as marking literal data, plus output-side sanity checks (wrong script,
hijack-shaped response, abnormal length) that fall back to the original text on any hit. See core/translation.py for
the fuller rationale.

This is defense in depth, not a guarantee: small local models are both more exploitable and less reliably steerable
than large hosted ones.
"""

from __future__ import annotations

import re
import secrets
from typing import Callable

from .languages import Language

# Phrases that suggest the model stopped translating and started reacting to something in the text as if it were an
# instruction (a successful prompt injection) rather than treating it as data to translate.
SUSPICIOUS_OUTPUT_PATTERNS = re.compile(
    r"(ignore (the |all )?(previous|prior|above) instructions?"
    r"|as an ai(?! subtitle)"
    r"|i cannot comply|i can(?:'|no)t assist"
    r"|new instructions?|system prompt|you are now"
    r"|\bjailbreak\b)",
    re.IGNORECASE,
)


def new_delimiter() -> str:
    """Return a random tag name for the sandbox delimiter of one job.

    The name is generated fresh and never derived from the input text, so whoever crafted a malicious input cannot
    predict or spoof it ahead of time.
    """
    return f"KVT_{secrets.token_hex(8)}"


def strip_delimiter_tags(text: str, delimiter: str) -> str:
    """Remove the sandbox delimiter tags if the model echoed them back in its output.

    Echoing the tags is a formatting slip rather than an attack, but they must not end up in the final result. The
    delimiter is generated by the app, so the removal is deterministic and does not depend on the model obeying the
    instruction not to echo it.
    """
    pattern = re.compile(rf"</?\s*{re.escape(delimiter)}\s*>", re.IGNORECASE)
    return pattern.sub("", text)


def clean_partial_output(text: str, delimiter: str) -> str:
    """Clean a partially generated answer for display while the translation streams in.

    Hides the sandbox tags the model may echo, including a tag that has only half arrived (a trailing "<KVT_ab"),
    which would otherwise flash on screen. The finished text still goes through sanitize_translation_output(); this
    function never decides what is kept.
    """
    text = strip_delimiter_tags(text, delimiter)
    for tag in (f"<{delimiter}>", f"</{delimiter}>"):
        for length in range(len(tag) - 1, 0, -1):
            if text.endswith(tag[:length]):
                text = text[:-length]
                break
    return text.lstrip()


def contains_target_script(text: str, lang: Language) -> bool:
    """Return True if *text* has at least one character in a Unicode range of *lang*.

    A language without declared ranges (for example one that uses the Latin script) always passes.
    """
    if not lang.unicode_ranges:
        return True
    return any(
        start <= ch <= end
        for ch in text
        for start, end in lang.unicode_ranges
    )


def sanitize_translation_output(
    output: str,
    original_text: str,
    target_lang: Language,
    delimiter: str,
    on_progress: Callable[[str], None],
    preserve_newlines: bool = False,
) -> str:
    """Clean a raw LLM response and fall back to the original text if it looks wrong.

    The fallback applies when the output is in the wrong script, looks like a hijacked response, or is abnormally
    long. Every translation engine uses this function, so a fix to this logic is made in one place.

    Args:
        output: The raw model response.
        original_text: The source text, returned (stripped) on a fallback.
        target_lang: The language the output is expected to be in.
        delimiter: The per-job delimiter name from new_delimiter().
        on_progress: Receives a warning line on each fallback.
        preserve_newlines: Keep paragraph breaks (free text) instead of flattening to single spaces (subtitle lines).
    """
    output = strip_delimiter_tags(output, delimiter)
    if preserve_newlines:
        # Free text keeps its paragraph structure (a subtitle line never has
        # any, so the default below flattens everything to single spaces).
        output = re.sub(r"[^\S\n]+", " ", output)
        output = re.sub(r" ?\n ?", "\n", output)
        output = re.sub(r"\n{3,}", "\n\n", output).strip()
    else:
        output = re.sub(r"\s+", " ", output).strip()
    output = output.strip("'\"*_`")

    if output and not contains_target_script(output, target_lang):
        on_progress(
            f"Warning: Output does not appear to be {target_lang.name} "
            f"for: '{original_text[:40]}' — keeping original"
        )
        return original_text.strip()

    if SUSPICIOUS_OUTPUT_PATTERNS.search(output):
        on_progress(
            f"Warning: translation output looks like a hijacked response, not a "
            f"translation, for: '{original_text[:40]}' — keeping original"
        )
        return original_text.strip()

    if len(output) > max(len(original_text) * 4, 200):
        on_progress(
            f"Warning: translation output abnormally long for: "
            f"'{original_text[:40]}' — keeping original"
        )
        return original_text.strip()

    return output
